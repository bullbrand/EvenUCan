// EvenUCan Local AI - 10-pin-facts.js
// Answers pin questions (which GPIO is the RGB LED, is GPIO 4 safe, which pins to avoid) from the app's own pin
// data in js/wizard/12, instead of the language model. The on-computer model is too small to be reliable for pin
// numbers. Returns null for anything that is not a pin question, so the model answers those as before.
'use strict';

// Pins to avoid and the safe-pin order for the boards the app supports. The ESP32-S3 entries come from
// S3_AVOID / S3_ORDER in js/wizard/12; the others use the same rules written in that file's comments.
const PIN_FACT_BOARDS = {
  s3: {
    label: 'ESP32-S3 DevKitC-1',
    avoid: S3_AVOID,
    order: S3_ORDER
  },
  c3: {
    label: 'ESP32-C3 Super Mini',
    avoid: {2: 'boot strapping pin', 8: 'boot strapping pin (also the LED)', 9: 'BOOT button',
            20: 'serial programming pin', 21: 'serial programming pin', 5: 'ADC2, stops working while Wi-Fi is on'},
    order: ESP32C3_ORDER
  },
  esp8266: {
    label: 'Wemos D1 Mini (ESP8266)',
    avoid: {0: 'boot pin (D3)', 2: 'boot pin (D4)', 15: 'boot pin (D8)', 1: 'serial TX', 3: 'serial RX',
            6: 'flash', 7: 'flash', 8: 'flash', 9: 'flash', 10: 'flash', 11: 'flash'},
    order: ESP8266_ORDER
  },
  classic: {
    label: 'classic ESP32 DevKit',
    avoid: {6: 'flash', 7: 'flash', 8: 'flash', 9: 'flash', 10: 'flash', 11: 'flash',
            34: 'input only', 35: 'input only', 36: 'input only', 37: 'input only', 38: 'input only', 39: 'input only',
            0: 'boot pin', 12: 'boot pin', 1: 'USB serial TX', 3: 'USB serial RX',
            2: 'boot-sensitive (use last)', 5: 'boot-sensitive (use last)', 15: 'boot-sensitive (use last)'},
    order: ESP32_ORDER
  }
};

// Which board the question is about: named in the question, else the project's board, else the ESP32-S3 DevKitC-1
// (the app's default test board).
function pinFactBoard(question, boardLabel) {
  const text = (String(question || '') + ' ' + String(boardLabel || '')).toLowerCase();
  if (/esp32[- ]?s3|\bs3\b|devkitc/.test(text)) return 's3';
  if (/esp32[- ]?c3|super mini|\bc3\b/.test(text)) return 'c3';
  if (/8266|d1 ?mini|wemos/.test(text)) return 'esp8266';
  if (/esp32/.test(text)) return 'classic';
  return 's3';
}

// A short pin guide for the model's system prompt, built from the same tables as the lookup above.
function pinGuideForPrompt() {
  try {
    const boards = Object.values(PIN_FACT_BOARDS).map(b => {
      const avoid = Object.entries(b.avoid).map(([pin, why]) => `GPIO${pin} (${why})`).join('; ');
      return `- ${b.label}: safe pins in order ${b.order.join(', ')}. Avoid: ${avoid}.`;
    }).join('\n');
    return 'Pin rules (use only these pins for wires and code):\n' + boards +
      '\n- The ESP32-S3 DevKitC-1 onboard LED is an RGB LED on GPIO 48 (board v1.0) or GPIO 38 (v1.1): use rgbLedWrite, not digitalWrite.';
  } catch(e) {
    return '';
  }
}

// The reference file the model reads (ai-reference/pin-codes.md), built from the same tables as the lookup above.
// The app writes it on every start, so it always matches the tables in this build.
function buildPinReferenceMd() {
  let out = '# EvenUCan pin reference (authoritative)\n\n' +
    'The assistant must check this file before answering from its own memory. Use only the pin numbers here for ' +
    'wires, code and wiring. If a pin is listed under Avoid, do not use it for a wire, and say why.\n\n' +
    'Generated by the app from its pin tables (js/wizard/12 and js/ai/10-pin-facts.js). Do not edit by hand.\n\n';
  Object.values(PIN_FACT_BOARDS).forEach(b => {
    out += '## ' + b.label + '\n\n';
    out += 'Safe pins, best first: ' + b.order.join(', ') + '.\n\n';
    out += 'Avoid:\n';
    Object.entries(b.avoid).forEach(([pin, why]) => { out += '- GPIO ' + pin + ': ' + why + '\n'; });
    out += '\n';
  });
  out += '## Default I2C pins (SDA, SCL)\n\n';
  Object.entries(PIN_FACT_I2C).forEach(([key, [sda, scl]]) => {
    out += '- ' + PIN_FACT_BOARDS[key].label + ': SDA GPIO ' + sda + ', SCL GPIO ' + scl + '\n';
  });
  out += '\n';
  out += '## ESP32-S3 DevKitC-1 onboard LED\n\n' +
    'The onboard LED is an RGB (WS2812-style) LED. It is on GPIO 48 (board v1.0) or GPIO 38 (board v1.1). ' +
    'Use rgbLedWrite(pin, red, green, blue) in Arduino-ESP32 3.x, or an ESPHome esp32_rmt_led_strip light with ' +
    'chipset ws2812. digitalWrite does nothing to it.\n';
  return out;
}

// Sends the built reference to the local server, which saves it beside the app. Quiet if the server is not there.
function publishPinReference() {
  try {
    if (!/^https?:$/.test(location.protocol)) return;
    const md = buildPinReferenceMd();
    fetch('/api/ai/reference', { method: 'POST', headers: { 'Content-Type': 'text/markdown; charset=utf-8' }, body: md })
      .catch(() => {});
  } catch (e) {}
}
document.addEventListener('DOMContentLoaded', publishPinReference);

// The default I2C pins (SDA, SCL) for each board, from the app's board data (js/wizard/03 and js/wizard/12).
const PIN_FACT_I2C = { s3: [8, 9], c3: [6, 7], esp8266: [4, 5], classic: [21, 22] };

function pinFactAnswer(question, boardLabel) {
  const q = String(question || '').toLowerCase();
  const pinMatch = /\b(?:gpio|pin|io)\s*-?\s*(\d{1,2})\b/.exec(q);
  const asksRgb = /\b(rgb|onboard|on-board|built[- ]?in)\b/.test(q) && /\bled\b/.test(q);
  const asksSafe = /\b(safe|free|avoid|which pins?|best pins?|not use|shouldn'?t use|can i use|reserved)\b/.test(q);
  const asksI2c = /\b(sda|scl|i2c)\b/.test(q);
  if (!pinMatch && !asksRgb && !asksSafe && !asksI2c) return null;

  const key = pinFactBoard(question, boardLabel);
  const board = PIN_FACT_BOARDS[key];
  const avoid = board.avoid;

  if (asksI2c && PIN_FACT_I2C[key]) {
    const [sda, scl] = PIN_FACT_I2C[key];
    return `On the ${board.label}, the default I2C pins are SDA = GPIO ${sda} and SCL = GPIO ${scl}. ` +
      `Other free pins can be used for I2C if the code sets them.`;
  }

  if (asksRgb && key === 's3') {
    const rgb = Object.entries(avoid).filter(([, why]) => /RGB/i.test(why)).map(([pin]) => pin);
    return `The onboard LED on the ${board.label} is an RGB (WS2812-style) LED on ` +
      `GPIO ${rgb.join(' or GPIO ')} (${rgb.length > 1 ? 'board v1.1 is 38, v1.0 is 48' : 'the pin on your board'}).\n\n` +
      `A plain \`digitalWrite\` does nothing to it. Use \`rgbLedWrite(pin, red, green, blue)\` in Arduino-ESP32 3.x, ` +
      `or an ESPHome \`esp32_rmt_led_strip\` light with \`chipset: ws2812\`.`;
  }

  if (pinMatch) {
    const n = Number(pinMatch[1]);
    const label = `GPIO ${n} on the ${board.label}`;
    if (avoid[n] !== undefined) return `${label}: ${avoid[n]}. Don't use it for a wire.`;
    if (board.order.includes(n)) return `${label} is a free pin you can use for a wire (it is on the safe-pin list).`;
    return `${label} is not on the safe-pin list. Pick one of: ${board.order.join(', ')}.`;
  }

  // A general question about safe or avoided pins
  const avoidList = Object.entries(avoid).map(([pin, why]) => `- GPIO ${pin}: ${why}`).join('\n');
  return `Safe pins on the ${board.label}, best first: ${board.order.join(', ')}.\n\nAvoid:\n${avoidList}`;
}
