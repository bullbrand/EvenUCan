// Regenerates js/data/curated-parts.js from parts-curated.json (only parts with status "curated").
// Usage: node tools/build-curated.js [--check]     (--check only compares, writes nothing)
// Logic taken from the build.js of the previous single-file build.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const jsonFile = process.env.CURATED_JSON || path.join(root, 'parts-curated.json');
const outFile = path.join(root, 'js', 'data', 'curated-parts.js');
const parts = JSON.parse(fs.readFileSync(jsonFile, 'utf8')).parts.filter(p => p.status === 'curated').map(p => {
  const board = p.type === 'board';
  const pins = (p.pins || []).map(q => {
    let r = q.r, n = q.n;
    // on a controller board "sig" would mean "needs a signal wire" and sda/scl would mean a peripheral's I2C pin
    if (board && r === 'sig') r = 'nc';
    else if (board && (r === 'sda' || r === 'scl')) { r = 'gpio'; if (n !== 'SDA' && n !== 'SCL') n += ' (' + (q.r === 'sda' ? 'SDA' : 'SCL') + ')'; }
    const o = { n, r, x: q.x, y: q.y }; if (q.g !== undefined) o.g = q.g; return o;
  });
  const o = { id: p.id, name: p.name + ' (curated)', type: p.type, shape: 'rect', w: p.w, d: p.d, pcb: p.pcb, h: p.h, below: p.below, mount: p.mount === 'wall' || p.mount === 'outside' ? p.mount : 'floor',
    features: p.features, pins, acc: p.confidence === 'low' ? 'approx' : 'drawing',
    notes: (p.notes || '') + ' Sources: ' + (p.sources || []).map(s => s.url).join(' ') };
  if (board && /esp32-?s3/i.test(p.name)) o.mcu = 'esp32s3'; // so the wiring and ESPHome code know the chip
  if (p.colour) o.colour = p.colour; // LED parts: the user picks the colour in the part editor
  return o;
});
const text = '// GENERATED by tools/build-curated.js from parts-curated.json (approved parts only). Do not edit by hand.\n' +
  'const CURATED_PARTS=' + JSON.stringify(parts) + ';\n';
const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
const norm = s => s.replace(/\r\n/g, '\n').replace(/^\/\/ GENERATED[^\n]*\n/, '');
console.log('curated parts:', parts.length);
if (process.argv.includes('--check')) { console.log(norm(cur) === norm(text) ? 'SAME as the file in js/data/' : 'DIFFERENT from the file in js/data/'); process.exit(norm(cur) === norm(text) ? 0 : 1); }
fs.writeFileSync(outFile, text);
console.log('wrote', path.relative(root, outFile), text.length, 'chars');
