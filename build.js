// Stitches src/ into app/EvenUCan.html (the single file Electron and web.zip ship).
// Every "<!-- INJECT path -->" line in src/index.html is replaced by that file's exact bytes
// (paths relative to src/). Zero dependencies. Usage: node build.js
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const src=path.join(__dirname,'src'),out=path.join(__dirname,'app','EvenUCan.html');

// Curated parts: boards approved with tools/curate-parts.js (status "curated" in app/parts-curated.json) are
// copied into src/js/parts-curated.js, which the app adds to its built-in parts list. If the JSON is not
// there (e.g. a fresh clone) the committed src/js/parts-curated.js is used as it is.
// Set CURATED_JSON=<path> to read it from somewhere else.
const curJson=process.env.CURATED_JSON||path.join(__dirname,'app','parts-curated.json');
if(fs.existsSync(curJson)){
  const parts=JSON.parse(fs.readFileSync(curJson,'utf8')).parts.filter(p=>p.status==='curated').map(p=>{
    const board=p.type==='board';
    const pins=(p.pins||[]).map(q=>{
      let r=q.r,n=q.n;
      // on a controller board "sig" would mean "needs a signal wire" and sda/scl would mean a peripheral's I2C pin
      if(board&&r==='sig')r='nc';
      else if(board&&(r==='sda'||r==='scl')){r='gpio';if(n!=='SDA'&&n!=='SCL')n+=' ('+(q.r==='sda'?'SDA':'SCL')+')';}
      const o={n,r,x:q.x,y:q.y};if(q.g!==undefined)o.g=q.g;return o;});
    return {id:p.id,name:p.name+' (curated)',type:p.type,shape:'rect',w:p.w,d:p.d,pcb:p.pcb,h:p.h,below:p.below,mount:'floor',
      features:p.features,pins,acc:p.confidence==='low'?'approx':'drawing',
      notes:(p.notes||'')+' Sources: '+(p.sources||[]).map(s=>s.url).join(' ')};
  });
  fs.writeFileSync(path.join(src,'js','parts-curated.js'),
    '// GENERATED by build.js from app/parts-curated.json (approved parts only). Do not edit by hand.\n'+
    'const CURATED_PARTS='+JSON.stringify(parts)+';\n');
  console.log('curated parts:',parts.length);
}
const html=fs.readFileSync(path.join(src,'index.html'),'utf8').replace(/^<!-- INJECT (\S+) -->\r?\n/gm,
  (m,p)=>fs.readFileSync(path.join(src,p),'utf8'));
fs.writeFileSync(out,html);
console.log('built app/EvenUCan.html',Buffer.byteLength(html),'bytes sha256',
  crypto.createHash('sha256').update(html).digest('hex'));
